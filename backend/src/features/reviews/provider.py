"""The contract every LLM provider implements, and the failures they all report the same way."""

import logging
from typing import Protocol

from pydantic import ValidationError

from src.features.projects.schemas import ProjectReview
from src.features.reviews.schemas import ReviewPrompt

logger = logging.getLogger(__name__)

MAX_OUTPUT_TOKENS = 16_000


class ReviewProvider(Protocol):
    """Makes a single review request; `service.request_review` owns retries."""

    async def generate(self, prompt: ReviewPrompt) -> ProjectReview: ...


class ReviewError(Exception):
    """A review attempt failed for a reason other than an API error."""

    retryable = False

    def __init__(self, message: str, *, request_id: str | None = None) -> None:
        super().__init__(message)
        self.request_id = request_id


class ReviewRefusedError(ReviewError):
    """The model (and any fallback) declined the request. Retrying would decline again."""


class MalformedReviewError(ReviewError):
    """The response was truncated, empty or did not match `ProjectReview`."""

    retryable = True


def validate_review_text(text: str, *, request_id: str | None) -> ProjectReview:
    """Validate the model's JSON output against `ProjectReview`."""
    if not text.strip():
        raise MalformedReviewError("Response contained no review text", request_id=request_id)
    try:
        return ProjectReview.model_validate_json(text)
    except ValidationError as exc:
        first = exc.errors()[0]
        location = ".".join(str(part) for part in first["loc"]) or "response"
        raise MalformedReviewError(
            f"Review did not match the expected format ({location}: {first['msg']})",
            request_id=request_id,
        ) from exc


def log_usage(
    model: str, request_id: str | None, input_tokens: int | None, output_tokens: int | None
) -> None:
    logger.info(
        "Review generated by %s (request_id=%s, input_tokens=%s, output_tokens=%s)",
        model,
        request_id,
        input_tokens,
        output_tokens,
    )

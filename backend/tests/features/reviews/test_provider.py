import json
import logging

import pytest

from src.features.projects.schemas import ProjectReview
from src.features.reviews.provider import (
    MalformedReviewError,
    ReviewError,
    ReviewRefusedError,
    log_usage,
    validate_review_text,
)
from tests.features.reviews.fakes import VALID_REVIEW

# --- validate_review_text -----------------------------------------------------------------------


def test_valid_json_becomes_a_review() -> None:
    review = validate_review_text(json.dumps(VALID_REVIEW), request_id="req_1")

    assert review == ProjectReview.model_validate(VALID_REVIEW)


@pytest.mark.parametrize("text", ["", "   ", "\n\t"])
def test_blank_text_is_malformed(text: str) -> None:
    with pytest.raises(MalformedReviewError, match="no review text") as info:
        validate_review_text(text, request_id="req_blank")

    assert info.value.request_id == "req_blank"
    assert info.value.retryable is True


def test_non_object_json_reports_the_whole_response() -> None:
    with pytest.raises(MalformedReviewError, match=r"\(response: ") as info:
        validate_review_text("[1, 2, 3]", request_id=None)

    assert info.value.request_id is None


def test_missing_field_is_named_in_the_error() -> None:
    body = {key: value for key, value in VALID_REVIEW.items() if key != "tags"}

    with pytest.raises(MalformedReviewError, match=r"\(tags: Field required\)"):
        validate_review_text(json.dumps(body), request_id="req_2")


def test_nested_field_location_uses_dots() -> None:
    body = {**VALID_REVIEW, "risks": ["Vendor lock-in", 42]}

    with pytest.raises(MalformedReviewError, match=r"\(risks\.1: Input should be a valid string"):
        validate_review_text(json.dumps(body), request_id="req_3")


def test_invalid_json_is_malformed_and_chains_the_cause() -> None:
    with pytest.raises(MalformedReviewError, match="did not match the expected format") as info:
        validate_review_text("not json", request_id="req_4")

    assert info.value.__cause__ is not None


# --- error classes ------------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("error_cls", "retryable"),
    [(ReviewError, False), (ReviewRefusedError, False), (MalformedReviewError, True)],
)
def test_retryable_defaults(error_cls: type[ReviewError], retryable: bool) -> None:
    error = error_cls("boom", request_id="req_x")

    assert error.retryable is retryable
    assert error.request_id == "req_x"
    assert str(error) == "boom"


def test_request_id_defaults_to_none() -> None:
    assert ReviewError("boom").request_id is None


# --- log_usage ----------------------------------------------------------------------------------


def test_log_usage_tolerates_missing_counts(caplog: pytest.LogCaptureFixture) -> None:
    with caplog.at_level(logging.INFO, logger="src.features.reviews.provider"):
        log_usage("gpt-test", None, None, None)

    assert "Review generated by gpt-test" in caplog.text
    assert "request_id=None, input_tokens=None, output_tokens=None" in caplog.text


def test_log_usage_reports_counts(caplog: pytest.LogCaptureFixture) -> None:
    with caplog.at_level(logging.INFO, logger="src.features.reviews.provider"):
        log_usage("claude-test", "req_9", 120, 40)

    assert "(request_id=req_9, input_tokens=120, output_tokens=40)" in caplog.text
